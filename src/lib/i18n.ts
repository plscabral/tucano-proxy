const dicts: Record<Locale, Dict> = { en, "pt-BR": ptBR, "pt-PT": ptPT, es };

const KEY = "tucano:locale";
const detected = (): Locale => {
  const saved = localStorage.getItem(KEY) as Locale | null;
  if (saved && dicts[saved]) return saved;
  const nav = (navigator.language || "en").toLowerCase();
  if (nav.startsWith("pt-br") || nav === "pt") return "pt-BR";
  if (nav.startsWith("pt")) return "pt-PT";
  if (nav.startsWith("es")) return "es";
  return "en";
};

const [locale, setLocaleSignal] = createSignal<Locale>(detected());

export const setLocale = (l: Locale) => {
  setLocaleSignal(l);
  localStorage.setItem(KEY, l);
  document.documentElement.setAttribute("lang", l);
};
document.documentElement.setAttribute("lang", locale());

export const t = (
  key: string,
  vars?: Record<string, string | number>,
): string => {
  const d = dicts[locale()] || en;
  let s = d[key] ?? en[key] ?? key;
  if (vars)
    for (const [k, v] of Object.entries(vars))
      s = s.replaceAll(`{${k}}`, String(v));
  return s;
};

export const currentLocale = locale;
